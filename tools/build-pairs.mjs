// Dev-only: checks tools/pair-candidates.txt against the puzzle-word graph and writes src/logic/pairs.js.
//   node tools/build-pairs.mjs          (prints what was kept and dropped)
// A pair is kept when both words are good endpoints and the shortest climb through puzzle words is 2-9 steps.
import { readFileSync, writeFileSync } from 'node:fs'
import { isEndpoint, isPuzzle } from '../src/logic/words.js'
import { distance } from '../src/logic/graph.js'

const here = new URL('.', import.meta.url)
const text = readFileSync(new URL('pair-candidates.txt', here), 'utf8').split('\n').filter((l) => !l.startsWith('#')).join(',')
const seen = new Set(), kept = [], dropped = []
for (const chunk of text.split(',')) {
  const [a, b] = chunk.trim().split(/\s+/)
  if (!a || !b) continue
  const key = a + ' ' + b
  if (seen.has(key)) continue
  seen.add(key)
  if (a.length !== b.length || !isEndpoint(a) || !isEndpoint(b)) { dropped.push(key + ' (word)'); continue }
  const par = distance(a, b, isPuzzle)
  if (par < 2 || par > 9) { dropped.push(`${key} (par ${par})`); continue }
  kept.push([a, b, par])
}
const rows = []
for (let i = 0; i < kept.length; i += 6) rows.push('  ' + kept.slice(i, i + 6).map(([a, b, p]) => `['${a}', '${b}', ${p}],`).join(' '))
writeFileSync(new URL('../src/logic/pairs.js', here), `// Hand-picked ladders with a little story to them: [start, goal, par]. Par is the fewest steps through puzzle words.
// GENERATED by tools/build-pairs.mjs from tools/pair-candidates.txt; tests/pairs.test.js re-checks every par.
// Dailies pick from this list by index, so only ever APPEND (via the candidates file); never reorder or remove.
export const PAIRS = [
${rows.join('\n')}
]
`)
const by = {}
for (const [a, , p] of kept) { const k = a.length + ':' + p; by[k] = (by[k] || 0) + 1 }
console.log('kept', kept.length, JSON.stringify(by))
console.log('dropped', dropped.length + ':', dropped.join(', '))
