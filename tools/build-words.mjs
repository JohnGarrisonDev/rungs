// Dev-only: rebuilds src/data/guess.js (every ENABLE word of 3-5 letters) and src/data/puzzle.js (the curated
// puzzle words from tools/puzzle-words.txt, intersected with ENABLE, minus the blocklist).
//   node tools/build-words.mjs path/to/enable1.txt
// ENABLE is public domain. WARNING: changing puzzle.js changes generated ladders (see AGENTS.md).
import { readFileSync, writeFileSync } from 'node:fs'
import { BLOCKLIST } from '../src/logic/blocklist.js'

const enablePath = process.argv[2]
if (!enablePath) { console.error('usage: node tools/build-words.mjs path/to/enable1.txt'); process.exit(1) }
const here = new URL('.', import.meta.url)
const LENS = [3, 4, 5]
const enable = readFileSync(enablePath, 'utf8').split(/\s+/).filter((w) => /^[a-z]+$/.test(w))
const guess = {}, guessSet = new Set()
for (const n of LENS) { guess[n] = enable.filter((w) => w.length === n).sort(); for (const w of guess[n]) guessSet.add(w) }

const src = readFileSync(new URL('puzzle-words.txt', here), 'utf8').split('\n').filter((l) => !l.startsWith('#')).join(' ')
const tokens = src.split(/\s+/).filter((w) => /^[a-z]+$/.test(w))
const puzzle = {}, dropped = []
for (const n of LENS) puzzle[n] = new Set()
for (const w of tokens) {
  if (!LENS.includes(w.length)) { dropped.push(w + ' (length)'); continue }
  if (!guessSet.has(w)) { dropped.push(w + ' (not in ENABLE)'); continue }
  if (BLOCKLIST.has(w)) { dropped.push(w + ' (blocked)'); continue }
  puzzle[w.length].add(w)
}
const pack = (obj) => LENS.map((n) => `  ${n}: '${[...obj[n]].sort().join('')}',`).join('\n')
writeFileSync(new URL('../src/data/guess.js', here), `// GENERATED by tools/build-words.mjs. Every 3, 4 and 5 letter word of the public-domain ENABLE word list,\n// packed end to end (fixed width, sorted). Any of these is accepted as a rung.\nexport const GUESS = {\n${pack(guess)}\n}\n`)
writeFileSync(new URL('../src/data/puzzle.js', here), `// GENERATED by tools/build-words.mjs from tools/puzzle-words.txt. Common, friendly words, packed end to end\n// (fixed width, sorted). Start words, goal words and the robot's route only use these.\n// Changing this list changes generated ladders: read AGENTS.md before you touch it.\nexport const PUZZLE = {\n${pack(puzzle)}\n}\n`)
for (const n of LENS) console.log(`${n} letters: guess ${guess[n].length}, puzzle ${puzzle[n].size}`)
if (dropped.length) console.log('dropped:', [...new Set(dropped)].join(', '))
